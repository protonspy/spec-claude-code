import "testing"

// TestTheHarnessDefaultsAreCaught is the test this package exists for: these are
// the exact footers Claude Code, Codex and opencode append when nothing tells
// them not to. If one of them stops being reported, the rule is back to being
// only a rule.
func TestTheHarnessDefaultsAreCaught(t *testing.T) {
	for _, tc := range []struct {
		name string
		text string
		rule string
	}{
		{"claude co-author", "fix: thing\n\nCo-Authored-By: Claude Opus 5 (1M context) <noreply@anthropic.com>", RuleTrailer},
		{"bare claude", "fix: thing\n\nCo-Authored-By: Claude <noreply@anthropic.com>", RuleTrailer},
		{"lowercase key", "fix: thing\n\nco-authored-by: Claude <x@example.com>", RuleTrailer},
		{"no hyphen", "fix: thing\n\nCoauthored-by: Claude <x@example.com>", RuleTrailer},
		{"leading space", "fix: thing\n\n  Co-Authored-By: Claude <x@example.com>", RuleTrailer},
		{"generated footer", "fix: thing\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)", RuleFooter},
		{"generated by", "fix: thing\n\nGenerated by Codex.", RuleFooter},
		{"created using", "fix: thing\n\nCreated using Cursor", RuleFooter},
		{"session link", "fix: thing\n\nSee https://claude.ai/chat/0d1e2f3a", RuleLink},
		{"vendor no-reply", "fix: thing\n\nReported-by: someone <noreply@anthropic.com>", RuleLink},
	} {
		t.Run(tc.name, func(t *testing.T) {
			hits := Scan(tc.text)
			if len(hits) != 1 {
				t.Fatalf("got %d hits, want 1: %+v", len(hits), hits)
			}
			if hits[0].Rule != tc.rule {
				t.Errorf("rule = %q, want %q", hits[0].Rule, tc.rule)
			}
			if hits[0].Line != 3 {
				t.Errorf("line = %d, want 3", hits[0].Line)
			}
		})
	}
}

// TestOrdinaryCommitsAreLeftAlone is the more important half. One false positive
// teaches the user to disbelieve every validator scc ships, so a name on the
// vocabulary is not on its own a reason to report anything.
func TestOrdinaryCommitsAreLeftAlone(t *testing.T) {
	for _, text := range []string{
		"chore(deps): bump the anthropic SDK to 0.40",
		"feat(harness): add opencode support",
		"feat(launch): start the agent inside ai-jail's sandbox with --jail",
		"docs: explain why the codex profile writes TOML",
		"fix(cli): stop claude-sonnet-5 being spelled two ways",
		// A commit that fixes this very finding quotes the line it removed.
		"fix(git): drop the co-author trailer\n\nThe trailer named an assistant.",
		// A real human sign-off, which the trailer rule must not touch.
		"fix: thing\n\nSigned-off-by: A Developer <dev@example.com>",
		// Bots that genuinely authored the commit they sign.
		"chore(deps): bump x\n\nCo-authored-by: dependabot[bot] <support@github.com>",
		// A person whose name contains a vocabulary entry that was removed for it.
		"fix: thing\n\nCo-authored-by: Champion Amparo <champ@example.com>",
		"",
	} {
		if hits := Scan(text); len(hits) != 0 {
			t.Errorf("Scan(%q) reported %+v, want nothing", text, hits)
		}
	}
}

// TestOneLineIsOneHit keeps the count honest: the harness footer carries a phrase
// and a link on the same line, and reporting it twice makes one mistake look like
// two.
func TestOneLineIsOneHit(t *testing.T) {
	hits := Scan("🤖 Generated with [Claude Code](https://claude.com/claude-code)")
	if len(hits) != 1 {
		t.Fatalf("got %d hits, want 1: %+v", len(hits), hits)
	}
	if hits[0].Rule != RuleFooter {
		t.Errorf("rule = %q, want %q", hits[0].Rule, RuleFooter)
	}
}

// TestAHitPointsAtItsLine: a finding is only actionable if it can point at the
// line it means, which is what makes `git show <sha>` a next step.
func TestAHitPointsAtItsLine(t *testing.T) {
	hits := Scan("subject\n\nbody\n\nCo-Authored-By: Claude <x@y.com>\n🤖 Generated with Claude Code")
	if len(hits) != 2 {
		t.Fatalf("got %d hits, want 2: %+v", len(hits), hits)
	}
	if hits[0].Line != 5 || hits[1].Line != 6 {
		t.Errorf("lines = %d, %d; want 5, 6", hits[0].Line, hits[1].Line)
	}
}

// TestCRLFScansTheSame — a message written on Windows is the same message.
func TestCRLFScansTheSame(t *testing.T) {
	hits := Scan("fix: thing\r\n\r\nCo-Authored-By: Claude <x@y.com>\r\n")
	if len(hits) != 1 || hits[0].Line != 3 {
		t.Fatalf("got %+v, want one hit on line 3", hits)
	}
	if got := hits[0].Match; got != "Co-Authored-By: Claude <x@y.com>" {
		t.Errorf("match = %q, carries a stray carriage return", got)
	}
}

